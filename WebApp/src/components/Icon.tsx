import opencode from '../assets/harness/opencode.svg?raw'

const HARNESS: Record<string, string> = {
  'grok-build': grok,
  codex: openai,
  claude,
  antigravity,
  copilot,
  cursor,
  opencode,
}
const maskCache = new Map<string, string>()
function maskFor(id: string): string | null {
  const svg = HARNESS[id]
  if (!svg) return null
  let url = maskCache.get(id)
  if (!url) {
    url = `url("data:image/svg+xml,${encodeURIComponent(svg)}")`
    maskCache.set(id, url)
  }
  return url
}

export function HarnessIcon({ id, size = 14 }: { id: string; size?: number }) {
  const mask = maskFor(id)
  if (!mask) return <Icon name="cpu" size={size} class="harness-fallback" />
  return (
    <span
      class="harness-icon"
      style={{ width: size, height: size, WebkitMaskImage: mask, maskImage: mask }}
    />
  )
}
